/**
 * 构造首轮用户消息：注入八字 JSON + 当前日期 + 用户问题。
 */
export function buildFirstUserMessage(chart: BaziChart, question: string): string {
  const today = new Date();
  const yyyy = today.getFullYear();
  const mm = String(today.getMonth() + 1).padStart(2, '0');
  const dd = String(today.getDate()).padStart(2, '0');

  const summary = {
    生辰: {
      公历: chart.solarString,
      农历: chart.lunarString,
      性别: chart.input.gender === 'male' ? '男' : '女',
      日历: chart.input.calendar === 'solar' ? '公历' : '农历',
      真太阳时: chart.input.useTrueSolarTime ? '已校正' : '未校正',
    },
    四柱: {
      年: chart.pillars.year,
      月: chart.pillars.month,
      日: chart.pillars.day,
      时: chart.pillars.hour,
    },
    日主: chart.dayMaster,
    五行统计: chart.wuXingCount,
    胎元: chart.taiYuan,
    命宫: chart.mingGong,
    身宫: chart.shenGong,
    起运: chart.yun,
    大运: chart.daYun,
  };

  return [
    `【排盘结果（JSON）】`,
    '```json',
    JSON.stringify(summary, null, 2),
    '```',
    '',
    `【当前公历日期】${yyyy}-${mm}-${dd}`,
    '',
    `【咨询问题】`,
    question,
  ].join('\n');
}
